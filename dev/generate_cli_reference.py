#!/usr/bin/env python3
"""Generate the command-line reference page.

Usage: uv run --project simulation_examples python dev/generate_cli_reference.py [--check]
"""

import argparse
import sys
import textwrap
from typing import Any

from cli_reference.commands import COMMANDS, Command, load
from cli_reference.options import Option, collect_sections
from config import REPO_ROOT, write_or_check

PAGE = REPO_ROOT / "docs" / "content" / "reference" / "command-line.md"
HEADER = """---
title: Command-line options
description: Every option of the eCoSim server, the clients and the HPC command.
---

<!-- Generated by dev/generate_cli_reference.py from the option definitions in the code. Do not edit by hand. -->

# Command-line options

These tables come from the option definitions in the code. `--help` shows the same. Every command also takes
`--help` and `--version`. A misspelled option or a wrong value stops the command with a short message, for
example `ecosim-server: error: argument --steps: must be a whole number of at least 1, not '0'`. For a misspelled
option the message suggests the closest one. The [exit codes](#exit-codes) are at the end of the page.

After changing an option, run `uv run --project simulation_examples python dev/generate_cli_reference.py` in the
repository root.
"""
TABLE_HEADER = ["| Option | Required | Default | Description |", "| --- | --- | --- | --- |"]


def render_row(option: Option) -> str:
    if option.flag:
        default = "flag"
    elif option.default is None:
        default = ""
    else:
        default = f"`{option.default}`"
    required = "yes" if option.required else ""
    value = f" {option.value}" if option.value else ""
    # | would end the table cell and < would start an HTML tag
    description = option.help.replace("|", "\\|").replace("<", "&lt;")
    return f"| `{option.name}{value}` | {required} | {default} | {description} |"


def examples_of(epilog: str | None) -> list[str]:
    """Return the example commands at the end of the help, without their indent."""
    if not epilog or not epilog.startswith("examples:"):
        return []
    return textwrap.dedent(epilog.removeprefix("examples:").strip("\n")).splitlines()


def render_command(command: Command, parsers: list[argparse.ArgumentParser]) -> list[str]:
    lines = [f"## {command.title}", ""]
    lines += [line for parser in parsers for line in (f"`{parser.prog}`: {parser.description}", "")]
    lines += [command.note, ""] if command.note else []
    examples = [example for parser in parsers for example in examples_of(parser.epilog)]
    lines += ["```shell", *examples, "```", ""] if examples else []
    for section in collect_sections(parsers[0]):
        lines += [f"**{section.title.capitalize()}**", "", *TABLE_HEADER, *(render_row(option) for option in section.options), ""]
    return lines


def render_exit_codes(shutdown_manager: Any, usage_error_exit_code: int) -> list[str]:
    return [
        "## Exit codes",
        "",
        "Every command ends with one of these codes. Without `--debug` an error ends the command with one line, for example:",
        "",
        "```text",
        "ecosim-server: error: No such file or directory: /home/user/building/Executable/../server/simulaton.json "
        + "(run with --debug for the full traceback)",
        "```",
        "",
        "With `--debug` the command shows the full traceback.",
        "",
        "| Code | When |",
        "| --- | --- |",
        f"| {shutdown_manager.SUCCESS_EXIT_CODE} | the run finished, or `--validate-fmu-file-only` found no problem |",
        f"| {shutdown_manager.FAILED_RUN_EXIT_CODE} | the run failed, or the command stopped on an error |",
        f"| {usage_error_exit_code} | an option is missing or has a wrong value |",
        f"| {shutdown_manager.INTERRUPT_EXIT_CODE} | Ctrl-C (SIGINT) during a run |",
        f"| {shutdown_manager.TERMINATE_EXIT_CODE} | SIGTERM, for example from `docker stop` or at the end of a SLURM job |",
        "",
    ]


def render_page(commands: list[list[str]], exit_codes: list[str]) -> str:
    return "\n".join([HEADER, *(line for command in commands for line in command), *exit_codes])


def main(arguments: list[str]) -> int:
    create_parser = load("ecosim_common.config.app_config.AppConfig").create_parser
    rendered = []
    for command in COMMANDS:
        parameters = load(command.arguments).parameters()
        console_scripts = [load(f"{module}.CONSOLE_SCRIPT") for module in command.console_script_modules]
        parsers = [
            create_parser(console_script=console_script, parameters=parameters, environment_variables={}) for console_script in console_scripts
        ]
        rendered.append(render_command(command=command, parsers=parsers))
    exit_codes = render_exit_codes(
        shutdown_manager=load("ecosim_common.tech.shutdown_manager.ShutdownManager"),
        usage_error_exit_code=load("ecosim_common.config.argument_parser.USAGE_ERROR_EXIT_CODE"),
    )
    return write_or_check(PAGE, render_page(commands=rendered, exit_codes=exit_codes), "--check" in arguments)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
