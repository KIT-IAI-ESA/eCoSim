#!/usr/bin/env python3
"""Generate the configuration reference page.

Usage: uv run python dev/generate_config_reference.py [--check]
"""

import json
import sys
from typing import Any

from config import REPO_ROOT, write_or_check
from config_reference.groups import GROUPS
from config_reference.keys import Enums, enum_members, extract_keys, render_keys
from config_reference.sections import INTERFACE_KEYS_TEXT, client_type_values, render_client_sections

PAGE = REPO_ROOT / "docs" / "content" / "reference" / "configuration-files.md"
SIMULATION_EXAMPLE = REPO_ROOT / "simulation_examples" / "building" / "server" / "simulation.json"
CLIENT_TYPE_FILE = REPO_ROOT / "ecosim-common" / "ecosim_common" / "client" / "config" / "client_type.py"
HEADER = """---
title: Configuration files
description: Every key the server and the clients read from their config files.
---

<!-- Generated by dev/generate_config_reference.py from the config readers in the code. Do not edit by hand. -->

# Configuration files

The server and the clients read ini files. These tables list every key the code reads. A key marked *required* has no default:
the program stops if it is missing. Enum values are written as the member name, for example `TCP_SOCKET`.
Values are read literally, so `%` has no special meaning and needs no escaping.
After changing a config reader, run `uv run python dev/generate_config_reference.py` in the repository root.
"""
SIMULATION_TEXT = """## Simulation config

The JSON file passed to `ecosim-server` with `--simulation-config` describes what is simulated:

- `simulators`: one entry per client with its `name`, `model` and `interfaces`. `connected_to` links
  an interface to an interface of a simulator, which is given by its position in `simulators`,
  counting from 0.
- `logical_delays`: connections whose values arrive a number of steps (`delay`, at least 1) later.
  Until then the receiving interface gets `start_value`. After a restore they start again with `start_value`,
  so the first steps after the restore can differ from a run without the abort.
- `setup.delta_t`: the step size in milliseconds. `--step-size` overrides it.
- `setup.start_date`: when the simulated time starts, by default `2024-01-01T00:00:00.000Z`. The results of the
  first step are stored one step later, at `start_date` plus `delta_t`. It only sets the time stamps of the steps
  and the stored results. The models always start at time 0.
  It needs a time zone offset (`Z` or `+01:00`). A value without one is rejected when the config is
  loaded.

Save the file as UTF-8, like the `.fmc` files.

The building example, shortened to its first simulator and two of its interfaces:
"""


def trim_simulation(config: dict[str, Any]) -> dict[str, Any]:
    first = dict(config["simulators"][0])
    first["interfaces"] = first.get("interfaces", [])[:2]
    return {**config, "simulators": [first]}


def all_enums() -> Enums:
    enums: Enums = {}
    for path in REPO_ROOT.glob("ecosim-*/ecosim_*/**/*.py"):
        enums.update(enum_members(path.read_text(encoding="utf-8")))
    return enums


def render_simulation_example() -> str:
    example = trim_simulation(json.loads(SIMULATION_EXAMPLE.read_text(encoding="utf-8")))
    return "\n".join([SIMULATION_TEXT, "```json", json.dumps(example, indent=2), "```", ""])


def render_page() -> str:
    enums = all_enums()
    parts = [HEADER]
    for title, intro, file in GROUPS:
        keys = extract_keys((REPO_ROOT / file).read_text(encoding="utf-8"), enums)
        parts += [f"## {title}", "", intro, "", render_keys(keys), ""]
    client_types = client_type_values(CLIENT_TYPE_FILE.read_text(encoding="utf-8"))
    parts += [render_client_sections(client_types), render_simulation_example(), INTERFACE_KEYS_TEXT]
    return "\n".join(parts)


def main(arguments: list[str]) -> int:
    return write_or_check(PAGE, render_page(), "--check" in arguments)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
